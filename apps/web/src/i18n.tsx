interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (source: string, variables?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

function translate(locale: Locale, source: string, variables?: Record<string, string | number>) {
  let result = locale === "fr" ? (french[source] ?? source) : source;
  for (const [key, value] of Object.entries(variables ?? {})) {
    result = result.replaceAll(`{${key}}`, String(value));
  }
  return result;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() =>
    window.localStorage.getItem(STORAGE_KEY) === "fr" ? "fr" : "en");

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(STORAGE_KEY, locale);
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (source, variables) => translate(locale, source, variables)
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function LanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className={`language-switcher${compact ? " compact" : ""}`} role="group" aria-label={t("Language")}>
      <button type="button" className={locale === "en" ? "active" : ""} onClick={() => setLocale("en")} aria-pressed={locale === "en"}>EN</button>
      <button type="button" className={locale === "fr" ? "active" : ""} onClick={() => setLocale("fr")} aria-pressed={locale === "fr"}>FR</button>
    </div>
  );
}

export function localizedStatusName(locale: Locale, key: string, fallback: string) {
  const names: Record<string, string> = {
    todo: translate(locale, "To do"),
    in_progress: translate(locale, "In progress"),
    blocked: locale === "fr" ? "Bloquée" : "Blocked",
    done: locale === "fr" ? "Terminée" : "Done",
    cancelled: translate(locale, "Cancelled")
  };
  return names[key] ?? fallback;
}
